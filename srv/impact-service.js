import cds from "@sap/cds";
import Ajv from "ajv";

import analysisSchema from "./lib/analysis-schema.js";
import { buildMessages } from "./lib/prompt.js";
import { analyzeWithOllama } from "./lib/ollama-client.js";

const { SELECT, INSERT, UPDATE, DELETE } = cds.ql;

const ajv = new Ajv({
  allErrors: true,
  strict: false
});

const validateAnalysis = ajv.compile(analysisSchema);

export default cds.service.impl(async function () {
  const {
    ChangeRequests,
    Impacts,
    Risks,
    TestScenarios,
    OpenQuestions
  } = this.entities;

  /*
   * ============================================================
   * ANALYZE CHANGE
   * ============================================================
   */
  this.on("analyze", "ChangeRequests", async (req) => {
    const id = req.params?.[0]?.ID;

    if (!id) {
      return req.reject(400, "Change request ID is required.");
    }

    // CAP automatically manages the request transaction.
    const change = await SELECT.one
      .from(ChangeRequests)
      .where({ ID: id });

    if (!change) {
      return req.reject(404, "Change request not found.");
    }

    if (!change.description?.trim()) {
      return req.reject(
        400,
        "Please enter a change description before starting analysis."
      );
    }

    await UPDATE(ChangeRequests)
      .set({
        status: "Analyzing"
      })
      .where({ ID: id });

    const startedAt = Date.now();

    try {
      /*
       * --------------------------------------------------------
       * 1. Build safe prompt
       * --------------------------------------------------------
       */
      const messages = buildMessages(change);

      /*
       * --------------------------------------------------------
       * 2. Call Ollama
       * --------------------------------------------------------
       */
      const aiResult = await analyzeWithOllama(messages);

      /*
       * --------------------------------------------------------
       * 3. Validate AI response
       * --------------------------------------------------------
       */
      const isValid = validateAnalysis(aiResult.data);

      if (!isValid) {
        const validationMessage = ajv.errorsText(
          validateAnalysis.errors,
          {
            separator: "; "
          }
        );

        throw new Error(
          `AI output failed schema validation: ${validationMessage}`
        );
      }

      const analysis = aiResult.data;

      /*
       * --------------------------------------------------------
       * 4. Delete results from an older analysis
       * --------------------------------------------------------
       */
      await DELETE.from(Impacts)
        .where({ change_ID: id });

      await DELETE.from(Risks)
        .where({ change_ID: id });

      await DELETE.from(TestScenarios)
        .where({ change_ID: id });

      await DELETE.from(OpenQuestions)
        .where({ change_ID: id });

      /*
       * --------------------------------------------------------
       * 5. Save impacts
       * --------------------------------------------------------
       */
      if (analysis.impacts.length > 0) {
        await INSERT.into(Impacts).entries(
          analysis.impacts.map((item) => ({
            change_ID: id,
            area: item.area,
            objectType: item.objectType,
            objectName: item.objectName,
            explanation: item.explanation,
            confidence: item.confidence
          }))
        );
      }

      /*
       * --------------------------------------------------------
       * 6. Save risks
       * --------------------------------------------------------
       */
      if (analysis.risks.length > 0) {
        await INSERT.into(Risks).entries(
          analysis.risks.map((item) => ({
            change_ID: id,
            title: item.title,
            severity: item.severity,
            explanation: item.explanation,
            mitigation: item.mitigation
          }))
        );
      }

      /*
       * --------------------------------------------------------
       * 7. Save proposed tests
       * --------------------------------------------------------
       */
      if (analysis.testScenarios.length > 0) {
        await INSERT.into(TestScenarios).entries(
          analysis.testScenarios.map((item) => ({
            change_ID: id,
            title: item.title,
            givenCondition: item.givenCondition,
            action: item.action,
            expectedResult: item.expectedResult,
            priority: item.priority
          }))
        );
      }

      /*
       * --------------------------------------------------------
       * 8. Save questions generated by the AI
       * --------------------------------------------------------
       */
      if (analysis.openQuestions.length > 0) {
        await INSERT.into(OpenQuestions).entries(
          analysis.openQuestions.map((item) => ({
            change_ID: id,
            question: item.question,
            reason: item.reason,
            resolved: false
          }))
        );
      }

      /*
       * If AI reports unresolved questions, require human review.
       */
      const status =
        analysis.openQuestions.length > 0
          ? "ReviewRequired"
          : "Analyzed";

      const processingMs = Date.now() - startedAt;

      await UPDATE(ChangeRequests)
        .set({
          status,
          modelName: aiResult.model,
          analyzedAt: new Date().toISOString(),
          processingMs,
          analysisVersion:
            Number(change.analysisVersion ?? 0) + 1
        })
        .where({ ID: id });

      return await SELECT.one
        .from(ChangeRequests)
        .where({ ID: id });
    } catch (error) {
      console.error(
        "[ImpactService] Ollama analysis failed:",
        error
      );

      /*
       * We attempt to record the failed state.
       */
      try {
        await UPDATE(ChangeRequests)
          .set({
            status: "Failed",
            processingMs: Date.now() - startedAt
          })
          .where({ ID: id });
      } catch (updateError) {
        console.error(
          "[ImpactService] Could not update failure status:",
          updateError
        );
      }

      return req.reject(
        502,
        `Change analysis failed: ${error.message}`
      );
    }
  });

  /*
   * ============================================================
   * APPROVE ANALYSIS
   * ============================================================
   */
  this.on("approve", "ChangeRequests", async (req) => {
    const id = req.params?.[0]?.ID;

    if (!id) {
      return req.reject(400, "Change request ID is required.");
    }

    const change = await SELECT.one
      .from(ChangeRequests)
      .where({ ID: id });

    if (!change) {
      return req.reject(404, "Change request not found.");
    }

    /*
     * Do not allow approval if AI has unanswered questions.
     */
    const unresolvedQuestions = await SELECT.from(OpenQuestions)
      .columns("ID")
      .where({
        change_ID: id,
        resolved: false
      });

    if (unresolvedQuestions.length > 0) {
      return req.reject(
        409,
        `Cannot approve this analysis. ${unresolvedQuestions.length} open question(s) still need to be resolved.`
      );
    }

    await UPDATE(ChangeRequests)
      .set({
        status: "Approved",
        approvedAt: new Date().toISOString(),
        approvedBy: req.user?.id ?? "unknown"
      })
      .where({ ID: id });

    return await SELECT.one
      .from(ChangeRequests)
      .where({ ID: id });
  });

  /*
   * ============================================================
   * REJECT ANALYSIS
   * ============================================================
   */
  this.on("reject", "ChangeRequests", async (req) => {
    const id = req.params?.[0]?.ID;

    if (!id) {
      return req.reject(400, "Change request ID is required.");
    }

    const change = await SELECT.one
      .from(ChangeRequests)
      .where({ ID: id });

    if (!change) {
      return req.reject(404, "Change request not found.");
    }

    await UPDATE(ChangeRequests)
      .set({
        status: "Rejected"
      })
      .where({ ID: id });

    return await SELECT.one
      .from(ChangeRequests)
      .where({ ID: id });
  });
});